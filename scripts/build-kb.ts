/**
 * Chat knowledge pipeline: reads /knowledge/*.md, splits each file into one chunk per
 * "## " heading and writes packages/shared/src/kb/kb.generated.ts.
 * Run with `npm run kb:build`; `dev` and `build` run it automatically.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SITE_PAGES } from "../packages/shared/src/constants";
import type { KbChunk, KnowledgeBase } from "../packages/shared/src/chat/kb-types";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(root, "knowledge");
const outFile = join(root, "packages/shared/src/kb/kb.generated.ts");
const knownPaths = new Set<string>(SITE_PAGES.map((p) => p.path));

function parseFrontMatter(raw: string, file: string): { meta: Record<string, string>; body: string } {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(raw);
  if (!match) throw new Error(`${file}: missing front matter`);
  const meta: Record<string, string> = {};
  for (const line of match[1]!.split(/\r?\n/)) {
    const idx = line.indexOf(":");
    if (idx > 0) meta[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  return { meta, body: match[2]! };
}

const splitList = (s: string) =>
  s
    .split(",")
    .map((k) => k.trim())
    .filter(Boolean);

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const files = readdirSync(sourceDir)
  .filter((f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md")
  .sort();

const chunks: KbChunk[] = [];
const hash = createHash("sha256");

for (const file of files) {
  const raw = readFileSync(join(sourceDir, file), "utf8");
  hash.update(file).update(raw);
  const { meta, body } = parseFrontMatter(raw, file);
  for (const key of ["title", "path", "pathLabel"]) {
    if (!meta[key]) throw new Error(`${file}: front matter needs "${key}"`);
  }
  if (!knownPaths.has(meta.path!)) throw new Error(`${file}: path "${meta.path}" is not in SITE_PAGES`);

  const docId = file.replace(/\.md$/, "");
  const docKeywords = splitList(meta.keywords ?? "");

  const sections = body.split(/^## /m).slice(1);
  if (sections.length === 0) throw new Error(`${file}: no "## " sections found`);
  for (const section of sections) {
    const newline = section.indexOf("\n");
    const heading = section.slice(0, newline).trim();
    let text = section.slice(newline + 1);
    let keywords: string[] = [];
    text = text.replace(/<!--\s*keywords:([\s\S]*?)-->/i, (_, list: string) => {
      keywords = splitList(list);
      return "";
    });
    chunks.push({
      id: `${docId}#${slug(heading)}`,
      docId,
      title: meta.title!,
      heading,
      path: meta.path!,
      pathLabel: meta.pathLabel!,
      keywords,
      docKeywords,
      text: text.trim(),
    });
  }
}

const kb: KnowledgeBase = { version: hash.digest("hex").slice(0, 12), chunks };
const output = `// Generated by scripts/build-kb.ts from /knowledge. Do not edit by hand.
import type { KnowledgeBase } from "../chat/kb-types";

export const KNOWLEDGE_BASE: KnowledgeBase = ${JSON.stringify(kb, null, 2)};
`;

mkdirSync(dirname(outFile), { recursive: true });
const unchanged = existsSync(outFile) && readFileSync(outFile, "utf8") === output;
if (!unchanged) writeFileSync(outFile, output);
console.log(
  `[kb] ${chunks.length} chunks from ${files.length} files (version ${kb.version})${unchanged ? ", unchanged" : ""}`,
);
